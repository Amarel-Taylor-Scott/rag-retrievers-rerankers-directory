"""Generate README.md from the curated retrievers/rerankers registry."""

from __future__ import annotations

from collections import defaultdict

from __version__ import __version__
from data import TOOLS, Category, Tool


def _badge(label: str, message: str, color: str) -> str:
    label = label.replace(" ", "%20")
    message = str(message).replace(" ", "%20").replace("-", "--")
    return f"![{label}](https://img.shields.io/badge/{label}-{message}-{color})"


def _source(t: Tool) -> str:
    if t.open_source:
        return "🟢 OSS"
    if t.license != "Proprietary":
        return "🔃 Source-available"
    return "🔒 Proprietary"


def _row(t: Tool) -> str:
    name = f"[{t.name}]({t.url})" if t.url else t.name
    return f"| {name} | {t.org} | {_source(t)} | {t.license} | {t.note} |"


def generate() -> str:
    total = len(TOOLS)
    oss = sum(1 for t in TOOLS if t.open_source)
    categories = sorted({t.category for t in TOOLS}, key=lambda c: c.label)

    by_cat: dict[Category, list[Tool]] = defaultdict(list)
    for t in TOOLS:
        by_cat[t.category].append(t)

    out: list[str] = []
    out.append("<!-- AUTO-GENERATED by report.py — run `python main.py generate` to refresh. -->")
    out.append("# 🔎 RAG Retrievers & Rerankers Directory\n")
    out.append(" ".join([
        _badge("version", __version__, "blue"),
        _badge("tools", total, "green"),
        _badge("open%20source", oss, "brightgreen"),
        _badge("categories", len(categories), "purple"),
        "[![CI](https://github.com/Amarel-Taylor-Scott/rag-retrievers-rerankers-directory/actions/workflows/ci.yml/badge.svg)]"
        "(https://github.com/Amarel-Taylor-Scott/rag-retrievers-rerankers-directory/actions/workflows/ci.yml)",
        "[![License: MIT](https://img.shields.io/badge/License-MIT-yellow.svg)](LICENSE)",
    ]))
    out.append("")
    out.append("> A curated, machine-readable directory of the **retrieval + reranking** layer of "
               "RAG — sparse/lexical retrieval, late-interaction retrieval, reranker libraries, "
               "open-weight reranker models, and managed reranking APIs.\n")
    out.append("Distinct from RAG *frameworks* (orchestration), *embedding models* (the vectors), "
               "and *vector databases* (storage): these tools *find and re-order* the most "
               "relevant passages. Ships a small CLI to search/filter/export.\n")

    out.append("## Quick start\n")
    out.append("```bash")
    out.append("pip install -e .                 # stdlib-only; no runtime deps")
    out.append("retriever-dir list               # list all")
    out.append("retriever-dir list --open-source # only OSS tools")
    out.append("retriever-dir list --category reranker_lib")
    out.append("retriever-dir search colbert     # search name/org/note/tags")
    out.append("retriever-dir export --format csv > retrievers.csv")
    out.append("retriever-dir generate           # regenerate this README")
    out.append("```\n")

    out.append("## At a glance\n")
    out.append(f"- **{total}** tools across **{len(categories)}** categories")
    out.append(f"- 🟢 **{oss}** open source · 🔒 **{total - oss}** proprietary / hosted\n")

    out.append("## Directory\n")
    for cat in sorted(by_cat, key=lambda c: c.label):
        tools = sorted(by_cat[cat], key=lambda t: t.name.lower())
        out.append(f"### {cat.label} ({len(tools)})\n")
        out.append("| Tool | Org | Source | License | Notes |")
        out.append("|------|-----|--------|---------|-------|")
        out.extend(_row(t) for t in tools)
        out.append("")

    out.append("## Choosing one (rules of thumb)\n")
    out.append("- **Lexical baseline:** rank_bm25, BM25S, Pyserini.")
    out.append("- **Strong neural retrieval:** ColBERT / RAGatouille (late interaction).")
    out.append("- **Rerank your top-k:** rerankers, FlashRank, Sentence-Transformers cross-encoders.")
    out.append("- **Don't run infra (hosted):** Cohere Rerank, Voyage AI, Jina Reranker.\n")

    out.append("## Legend\n")
    out.append("🟢 open source / open weights (license shown) · 🔃 source-available · "
               "🔒 proprietary / hosted.\n")

    out.append("## Contributing\n")
    out.append("Add or correct an entry in [`data.py`](data.py), run `python main.py generate`, "
               "and open a PR. See [CONTRIBUTING.md](CONTRIBUTING.md) and "
               "[CODE_OF_CONDUCT.md](CODE_OF_CONDUCT.md). Keep the focus on retrieval/reranking "
               "(not RAG orchestration or embedding models); record the EXACT license; omit "
               "anything you can't verify.\n")

    out.append("## License\n")
    out.append("[MIT](LICENSE) © Amarel Taylor Scott. Catalog metadata only; each tool's own "
               "license/terms govern its use.\n")
    return "\n".join(out)


if __name__ == "__main__":
    print(generate())
